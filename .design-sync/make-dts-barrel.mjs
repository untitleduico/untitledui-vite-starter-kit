// Generates dist/types/index.d.ts - the barrel the design-sync converter reads
// as the package's API contract.
//
// This repo is a Vite app, not a published library: it has no build that emits
// types, so `tsc --emitDeclarationOnly` produces dist/types and this script
// writes the barrel over it. Without a barrel every emitted <Name>Props comes
// out as `[key: string]: unknown` and the design agent gets no API at all.
//
// The barrel mirrors the JS synth entry exactly: the same src/components tree,
// the same three files held back because their export names collide with
// another file's, re-exported here under the same aliases as
// .design-sync/alias-exports.ts. JS entry and type entry must agree, or
// validate reports components that are typed but not on window.UntitledUI.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const TYPES_ROOT = "dist/types";
const COMPONENTS = join(TYPES_ROOT, "components");

// Kept out of the star-exports; re-exported under aliases below.
const EXCLUDE = [
    "components/base/buttons/app-store-buttons-outline.d.ts",
    "components/application/slideout-menus/slideout-menu.d.ts",
    "components/shared-assets/credit-card/icons.d.ts",
];

const walk = (dir, out = []) => {
    for (const name of readdirSync(dir)) {
        const p = join(dir, name);
        if (statSync(p).isDirectory()) walk(p, out);
        else if (p.endsWith(".d.ts")) out.push(p);
    }
    return out;
};

const files = walk(COMPONENTS)
    .map((p) => relative(TYPES_ROOT, p).split("\\").join("/"))
    .filter((p) => !EXCLUDE.includes(p))
    .sort();

const spec = (p) => "./" + p.replace(/\.d\.ts$/, "");

const lines = [
    "// GENERATED by .design-sync/make-dts-barrel.mjs - do not edit.",
    "// The API surface design-sync reads. Mirrors the JS bundle entry.",
    "",
    ...files.map((p) => `export * from ${JSON.stringify(spec(p))};`),
    "",
    "// Files held back above, re-exported under non-colliding names.",
    "export {",
    "    AppStoreButton as AppStoreButtonOutline,",
    "    GooglePlayButton as GooglePlayButtonOutline,",
    "    GalaxyStoreButton as GalaxyStoreButtonOutline,",
    "    AppGalleryButton as AppGalleryButtonOutline,",
    '} from "./components/base/buttons/app-store-buttons-outline";',
    'export { SlideoutMenu } from "./components/application/slideout-menus/slideout-menu";',
    "export {",
    "    Modal as SlideoutMenuModal,",
    "    Dialog as SlideoutMenuDialog,",
    "    ModalOverlay as SlideoutMenuModalOverlay,",
    '} from "./components/application/slideout-menus/slideout-menu";',
    'export { PaypassIcon, MastercardIconWhite } from "./components/shared-assets/credit-card/icons";',
    'export { MastercardIcon as CreditCardMastercardIcon } from "./components/shared-assets/credit-card/icons";',
    "",
];

writeFileSync(join(TYPES_ROOT, "index.d.ts"), lines.join("\n"));
console.error(`  [DTS_BARREL] dist/types/index.d.ts -> ${files.length} modules`);
